function RemoveAtAccountOnPlayer(src, where, priceremove)
    return ESX.GetPlayerFromId(src).removeAccountMoney(where, tonumber(priceremove))
end

function AddAtAccountOnPlayer(src, where, priceremove)
    return ESX.GetPlayerFromId(src).addAccountMoney(where, tonumber(priceremove))
end

function AddMoneyDrugsOnPlayer(src, priceremove)
    return ESX.GetPlayerFromId(src).addAccountMoney(ConfigContextMenu.Money.ArgentSale, tonumber(priceremove))
end

function SetJobPlayerJob(Player, JobName, newGrade)
    return Player.setJob(JobName, newGrade)
end

function SetJobPlayerOrga(Player, JobName, newGrade)
    return Player.setJob2(JobName, newGrade)
end

function GetJob(Player)
    return ESX.GetPlayerFromId(Player).getJob()
end

function GetJob2(Player)
    return ESX.GetPlayerFromId(Player).getJob2()
end
